"""Closed-form correctness tests for the pure-NumPy information-theoretic estimators.

Every assertion here compares a computed number against a value known
*independently* of the implementation (an analytic formula for the generating
process, or an information-theoretic inequality). This is the only place in the
suite where a ``return np.zeros(...)`` stub would be caught: the rest of the
tests check shape/finiteness or compare against a baseline generated by the same
code.

LOG BASE: every estimator in the module reports **nats**. `_expected` and
`BITS_ESTIMATORS` are where a base-2 estimator would have to declare itself,
rather than silently landing on an axis differing by a factor of ln 2.

Sampling: the Gaussian fixtures are whitened so the *sample* covariance equals
the target covariance exactly. Expectations are therefore computed from the
known rho of the generating process, never from ``np.corrcoef`` of the sample —
comparing against the sample correlation would reduce the Gaussian test to an
implementation identity that cannot detect a wrong rho or a wrong log base.
Whitening also removes the O(1/sqrt(N)) sampling noise in rho, which is what
lets the Gaussian tolerance be 1e-7 rather than 1e-2. Not tighter:
the Gaussian path ridge-regularises the covariance at 1e-8 relative
(the deterministic analogue of JIDT's NOISE_LEVEL_TO_ADD), so identities
assembled from several entropies cannot cancel below that order.
"""
import numpy as np
import pytest

from pyspi.data import Data
from pyspi.statistics.infotheory import (
    CausalEntropy,
    ConditionalEntropy,
    CrossmapEntropy,
    DirectedInfo,
    GaussianEntropyCalculator,
    JointEntropy,
    KLEntropyCalculator,
    KernelEntropyCalculator,
    MutualInfo,
    StochasticInteraction,
    TimeLaggedMutualInfo,
    TransferEntropy,
)

# Every estimator in the module reports nats; see InfoTheoryBase.
BITS_ESTIMATORS = frozenset()

N_LARGE = 20000
N_SMALL = 3000

# Per-estimator absolute tolerances against the analytic MI, in that
# estimator's own units. Gaussian is a closed form on an exactly-specified
# covariance, so it is held to round-off. The kNN and box-kernel estimators
# carry genuine O(1e-2) finite-sample bias at N=20000 (KSG k=4; box kernel at
# fixed bandwidth 0.25) — these are estimator properties, not slack chosen to
# make the test pass.
# 1e-7, not 1e-9: the Gaussian MI path goes through the same ridge as the
# entropy path, which biases it by ridge*r^2/(1-r^2) ~ 5.6e-9 at rho=0.6.
MI_ATOL = {"gaussian": 1e-7, "kraskov": 0.02, "kernel": 0.02, "kozachenko": 0.02}

_ESTIMATOR_KWARGS = {"kraskov": {"prop_k": 4}, "kernel": {"kernel_width": 0.25}}

# kozachenko is deliberately absent: MutualInfo and TimeLaggedMutualInfo are
# estimated directly rather than from marginal entropies, and there is no
# Kozachenko-Leonenko path for them. The constructor raises, so the
# combination is rejected rather than tested -- see
# test_smoke.test_kozachenko_rejected_for_non_entropy.
MI_ESTIMATORS = [
    "gaussian",
    "kraskov",
    "kernel",
    pytest.param("_removed_kozachenko", marks=pytest.mark.skip(
        reason="rejected at construction; see test_kozachenko_rejected_for_non_entropy",
    )),
]


def _expected(value_in_nats, estimator):
    """Analytic values need no conversion: the whole module reports nats.

    Kept as a function, and `BITS_ESTIMATORS` kept as an (empty) set, so that
    reintroducing a base-2 estimator has an obvious place to declare itself
    rather than silently landing on an axis differing by ln 2.
    """
    return value_in_nats / np.log(2) if estimator in BITS_ESTIMATORS else value_in_nats


def _spi(cls, estimator, **kwargs):
    return cls(estimator=estimator, **_ESTIMATOR_KWARGS.get(estimator, {}), **kwargs)


def _exact_gaussian_pair(rho, n=N_LARGE, seed=0):
    """Bivariate normal whose *sample* covariance is exactly [[1, rho], [rho, 1]]."""
    rng = np.random.default_rng(seed)
    Z = rng.standard_normal((2, n))
    Z = Z - Z.mean(axis=1, keepdims=True)
    Z = np.linalg.inv(np.linalg.cholesky(np.cov(Z, ddof=1))) @ Z
    return np.linalg.cholesky(np.array([[1.0, rho], [rho, 1.0]])) @ Z


def _ar1_with_drive(a, b, sigma=1.0, n=N_LARGE, seed=0):
    """y_t = a*y_{t-1} + b*x_{t-1} + sigma*eps_t, with x iid N(0, 1)."""
    rng = np.random.default_rng(seed)
    x = rng.standard_normal(n)
    eps = rng.standard_normal(n)
    y = np.zeros(n)
    for t in range(1, n):
        y[t] = a * y[t - 1] + b * x[t - 1] + sigma * eps[t]
    return np.vstack([x, y])


def _coupled_pair(coupling, n=N_SMALL, seed=0):
    """X -> Y at lag 1 with strength ``coupling`` (0 gives independent series)."""
    rng = np.random.default_rng(seed)
    x = rng.standard_normal(n)
    y = np.zeros(n)
    for t in range(1, n):
        y[t] = 0.5 * y[t - 1] + coupling * x[t - 1] + rng.standard_normal()
    return np.vstack([x, y])


# ---------------------------------------------------------------------------
# Mutual information against the exact bivariate-Gaussian value
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("estimator", MI_ESTIMATORS)
@pytest.mark.parametrize("rho", [0.0, 0.3, 0.6, 0.9])
def test_bivariate_gaussian_mi(estimator, rho):
    """MI of a bivariate normal is exactly -0.5*ln(1 - rho^2) nats."""
    data = Data(_exact_gaussian_pair(rho), zscore=False)
    result = _spi(MutualInfo, estimator).multivariate(data)

    assert result.shape == (2, 2)
    assert np.all(np.isnan(np.diag(result))), "diagonal must be NaN"

    expected = _expected(-0.5 * np.log(1.0 - rho ** 2), estimator)
    assert result[0, 1] == pytest.approx(result[1, 0], abs=1e-12), "MI must be symmetric"
    assert result[0, 1] == pytest.approx(expected, abs=MI_ATOL[estimator]), (
        f"{estimator} MI at rho={rho}: got {result[0, 1]}, expected {expected}"
    )


# ---------------------------------------------------------------------------
# Differential entropy of N(0, sigma^2)
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("sigma", [1.0, 2.0])
@pytest.mark.parametrize("estimator", ["gaussian", "kozachenko", "kernel"])
def test_gaussian_differential_entropy(estimator, sigma):
    """H[N(0, sigma^2)] = 0.5*ln(2*pi*e*sigma^2) nats.

    Exercises the entropy calculators directly rather than through a SPI,
    because Data() z-scores by default and would destroy sigma.
    """
    rng = np.random.default_rng(7)
    x = sigma * rng.standard_normal(N_LARGE)

    calc = {
        "gaussian": GaussianEntropyCalculator,
        "kozachenko": KLEntropyCalculator,
        "kernel": KernelEntropyCalculator,
    }[estimator]()
    calc.initialise(1)
    if estimator == "kernel":
        calc.setProperty("KERNEL_WIDTH", "0.25")
    calc.setObservations(x)
    got = calc.computeAverageLocalOfObservations()

    expected = _expected(0.5 * np.log(2 * np.pi * np.e * sigma ** 2), estimator)
    # Absolute, in the estimator's own units. All three are consistent (mean
    # error -> 0 with N) but noisy at finite N: the Kozachenko-Leonenko k=1
    # estimator has sd ~0.013 nats at N=20000, measured over 15 seeds, and the
    # box kernel carries a small bandwidth-dependent bias. 0.05 is ~4 sd, and
    # still 14x tighter than ln(2)=0.693 — the smallest error a wrong log base
    # or a dropped normalisation constant could produce.
    assert got == pytest.approx(expected, abs=0.05), (
        f"{estimator} H[N(0,{sigma}^2)]: got {got}, expected {expected}"
    )


# ---------------------------------------------------------------------------
# Gaussian transfer entropy on a known AR(1)-with-drive process
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("a, b", [(0.5, 0.6), (0.2, 0.9), (0.7, 0.3)])
def test_gaussian_te_ar1_analytic(a, b):
    """TE(X->Y) = 0.5*ln(var_reduced / var_full) for y_t = a y_{t-1} + b x_{t-1} + eps.

    x is iid and independent of y_{t-1}, so conditioning on y_{t-1} alone leaves
    residual variance b^2 var(x) + sigma^2, while conditioning on (y_{t-1},
    x_{t-1}) leaves sigma^2. TE(Y->X) is 0 because x has no history at all.
    """
    sigma = 1.0
    data = Data(_ar1_with_drive(a, b, sigma), zscore=True)
    result = TransferEntropy(estimator="gaussian").multivariate(data)

    expected = 0.5 * np.log((b ** 2 * 1.0 + sigma ** 2) / sigma ** 2)
    assert result[0, 1] == pytest.approx(expected, abs=0.01), (
        f"TE(X->Y): got {result[0, 1]}, expected {expected}"
    )
    assert abs(result[1, 0]) < 0.01, f"TE(Y->X) should vanish, got {result[1, 0]}"


@pytest.mark.parametrize("estimator, atol", [("gaussian", 0.01), ("kraskov", 0.02)])
def test_te_matches_the_closed_form_of_a_bivariate_var1_with_feedback(estimator, atol):
    """z_t = A z_{t-1} + e_t, z = (x, y), e ~ N(0, I), coupling in both directions.

    With k = l = 1 the full-past regression of y_{t+1} on (y_t, x_t) leaves the
    innovation variance 1, and the reduced one on y_t alone leaves
    Gamma0_yy - Gamma1_yy^2 / Gamma0_yy, where Gamma0 is the stationary
    covariance (discrete Lyapunov equation) and Gamma1 = A Gamma0 the lag-1
    covariance. So TE(X->Y) = 0.5*ln(Gamma0_yy - Gamma1_yy^2 / Gamma0_yy), and
    symmetrically for Y->X. Unlike the iid-driver test above, the source here
    has its own dynamics and is itself driven by the target, so a swapped
    index or a source embedding taken from the wrong series shows up in both
    entries. Tolerances are ~6 sampling SDs (gaussian: SD 0.0017 and 0.0006)
    and the KSG bias at N=20000, as in MI_ATOL.
    """
    from scipy.linalg import solve_discrete_lyapunov

    A = np.array([[0.6, 0.1], [0.4, 0.3]])     # x -> y strong, y -> x weak
    gamma0 = solve_discrete_lyapunov(A, np.eye(2))
    gamma1 = A @ gamma0
    expected = {
        (0, 1): 0.5 * np.log(gamma0[1, 1] - gamma1[1, 1] ** 2 / gamma0[1, 1]),
        (1, 0): 0.5 * np.log(gamma0[0, 0] - gamma1[0, 0] ** 2 / gamma0[0, 0]),
    }

    rng = np.random.default_rng(1)
    z = np.zeros((2, N_LARGE))
    e = rng.standard_normal((2, N_LARGE))
    for t in range(1, N_LARGE):
        z[:, t] = A @ z[:, t - 1] + e[:, t]

    result = _spi(TransferEntropy, estimator).multivariate(Data(z, zscore=True))
    for (i, j), value in expected.items():
        assert result[i, j] == pytest.approx(value, abs=atol), (
            f"{estimator} TE({i}->{j}): got {result[i, j]}, expected {value}")


# ---------------------------------------------------------------------------
# Independence: everything must collapse to ~0
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("cls", [MutualInfo, TimeLaggedMutualInfo, TransferEntropy])
@pytest.mark.parametrize("estimator", ["gaussian", "kraskov", "kernel"])
def test_independent_series_give_near_zero(cls, estimator):
    """X independent of Y => MI, TLMI and TE are ~0 for every estimator.

    This is the assertion a constant-returning stub cannot survive; `isfinite`
    checks elsewhere in the suite would pass one.

    The box-kernel TE is the one exception: at fixed bandwidth in the 3-D
    (y_next, y_past, x_past) space it carries a large positive finite-sample
    bias (~0.06 nats at N=10000, decaying with N). That is an estimator
    property, documented rather than hidden — the bias is still an order of
    magnitude below the coupled value, which is what
    ``test_coupling_increases_directed_measures`` checks.
    """
    data = Data(_coupled_pair(0.0, n=10000), zscore=True)
    result = _spi(cls, estimator).multivariate(data)
    off_diagonal = result[~np.isnan(result)]

    limit = 0.15 if (cls is TransferEntropy and estimator == "kernel") else 0.05
    assert np.max(np.abs(off_diagonal)) < limit, (
        f"{cls.__name__}/{estimator} on independent series: {result}"
    )


def test_symbolic_te_independent_series():
    """Symbolic TE (histogram-based) also collapses on independent data."""
    data = Data(_coupled_pair(0.0, n=10000), zscore=True)
    result = TransferEntropy(estimator="symbolic", k_history=3).multivariate(data)
    assert np.max(np.abs(result[~np.isnan(result)])) < 0.05, result


